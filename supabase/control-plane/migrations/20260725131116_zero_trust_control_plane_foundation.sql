create or replace function public.revoke_control_plane_permission(
  p_grant_code text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_grant private.control_plane_permission_grants%rowtype;
begin
  perform private.require_control_plane_operator(array['owner']);

  select * into v_grant
  from private.control_plane_permission_grants
  where grant_code = p_grant_code
    and revoked_at is null
  for update;

  if v_grant.id is null then
    raise exception 'control_plane_grant_not_found' using errcode = '22023';
