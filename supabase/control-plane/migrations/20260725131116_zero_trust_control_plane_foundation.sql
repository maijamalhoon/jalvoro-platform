  where id = v_grant.id;

  insert into private.control_plane_audit_events (
    actor_user_id, subject_user_id, grant_id, action, permission_key
  ) values (
    v_actor, v_grant.user_id, v_grant.id, 'permission_revoked', v_grant.permission_key
  );

  return jsonb_build_object(
    'grantCode', v_grant.grant_code,
    'status', 'revoked'
  );
end;
$$;

