create or replace function public.disable_control_plane_operator(
  p_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_operator private.control_plane_operators%rowtype;
begin
  perform private.require_control_plane_operator(array['owner']);

  select * into v_operator
  from private.control_plane_operators
  where user_id = p_user_id
  for update;

  if v_operator.user_id is null then
    raise exception 'control_plane_operator_not_found' using errcode = '22023';
  end if;

  if v_operator.is_root_owner then
    raise exception 'root_owner_cannot_be_disabled' using errcode = '42501';
  end if;

  update private.control_plane_operators
  set status = 'disabled',
      disabled_at = now(),
      disabled_by = v_actor,
      updated_at = now()
  where user_id = p_user_id;

  update private.control_plane_permission_grants
  set revoked_at = now(), revoked_by = v_actor
  where user_id = p_user_id and revoked_at is null;

  insert into private.control_plane_audit_events (
    actor_user_id, subject_user_id, action, previous_role
  ) values (
    v_actor, p_user_id, 'operator_disabled', v_operator.role
  );

  return jsonb_build_object(
    'userReference', private.control_plane_user_reference(p_user_id),
    'status', 'disabled'
  );
end;
$$;

revoke all on function public.disable_control_plane_operator(uuid)
  from public, anon;
grant execute on function public.disable_control_plane_operator(uuid)
  to authenticated;

create or replace function public.get_control_plane_directory()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_result jsonb;
begin
  perform private.require_control_plane_operator(array['owner']);

  select jsonb_build_object(
    'operators', coalesce((
      select jsonb_agg(jsonb_build_object(
        'userReference', private.control_plane_user_reference(o.user_id),
        'role', o.role,
        'isRootOwner', o.is_root_owner,
        'status', o.status,
        'createdAt', o.created_at,
        'disabledAt', o.disabled_at
      ) order by o.is_root_owner desc, o.created_at asc)
      from private.control_plane_operators o
    ), '[]'::jsonb),
    'pendingInvitations', coalesce((
      select jsonb_agg(jsonb_build_object(
        'invitationCode', i.invitation_code,
        'maskedEmail', i.intended_email_masked,
        'role', i.role,
        'expiresAt', i.expires_at
      ) order by i.created_at desc)
      from private.control_plane_invitations i
      where i.status = 'pending' and i.expires_at > now()
    ), '[]'::jsonb),
    'activeGrants', coalesce((
      select jsonb_agg(jsonb_build_object(
        'grantCode', g.grant_code,
        'userReference', private.control_plane_user_reference(g.user_id),
        'permissionKey', g.permission_key,
        'productKey', g.product_key,
        'moduleKey', g.module_key,
        'environmentKey', g.environment_key,
        'regionKey', g.region_key,
        'organizationId', g.organization_id,
        'dataClassification', g.data_classification,
        'expiresAt', g.expires_at
      ) order by g.granted_at desc)
      from private.control_plane_permission_grants g
      where g.revoked_at is null
        and (g.expires_at is null or g.expires_at > now())
    ), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;

revoke all on function public.get_control_plane_directory()
  from public, anon;
grant execute on function public.get_control_plane_directory()
  to authenticated;

commit;
