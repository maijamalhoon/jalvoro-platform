create or replace function private.mask_control_plane_email(p_email text)
returns text
language sql
immutable
strict
set search_path = pg_catalog
as $$
  select case
    when position('@' in p_email) <= 1 then 'hidden'
    else left(split_part(lower(trim(p_email)), '@', 1), 1)
      || repeat('*', greatest(2, least(char_length(split_part(lower(trim(p_email)), '@', 1)) - 1, 6)))
      || '@' || split_part(lower(trim(p_email)), '@', 2)
  end;
$$;

