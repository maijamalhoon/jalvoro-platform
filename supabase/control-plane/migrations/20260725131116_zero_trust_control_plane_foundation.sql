create or replace function private.require_control_plane_operator(
  p_allowed_roles text[] default null
)
returns text
language plpgsql
stable
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_user_id uuid := auth.uid();
  v_aal text := coalesce(auth.jwt()->>'aal', 'aal1');
  v_role text;
begin
  if v_user_id is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;

  if v_aal <> 'aal2' then
    raise exception 'mfa_verification_required' using errcode = '42501';
  end if;

  select role into v_role
  from private.control_plane_operators
  where user_id = v_user_id
    and status = 'active'
    and disabled_at is null;

  if v_role is null then
    raise exception 'control_plane_access_required' using errcode = '42501';
  end if;

  if p_allowed_roles is not null and not (v_role = any(p_allowed_roles)) then
    raise exception 'control_plane_role_required' using errcode = '42501';
  end if;

  return v_role;
end;
$$;

revoke all on function private.require_control_plane_operator(text[])
  from public, anon;
grant execute on function private.require_control_plane_operator(text[])
  to authenticated, service_role;

create or replace function private.bootstrap_control_plane_root_owner(p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_existing_root uuid;
begin
  if not exists (
    select 1 from auth.users
    where id = p_user_id and deleted_at is null
  ) then
    raise exception 'control_plane_owner_user_not_found' using errcode = '22023';
  end if;

  select user_id into v_existing_root
  from private.control_plane_operators
  where is_root_owner
  limit 1;

  if v_existing_root is not null and v_existing_root <> p_user_id then
    raise exception 'control_plane_root_owner_already_exists' using errcode = '23505';
  end if;

  insert into private.control_plane_operators (
    user_id, role, is_root_owner, status, created_by
  ) values (
    p_user_id, 'owner', true, 'active', p_user_id
  )
  on conflict (user_id) do update
  set role = 'owner',
      is_root_owner = true,
      status = 'active',
      disabled_at = null,
      disabled_by = null,
      updated_at = now();

  if not exists (
    select 1 from private.control_plane_audit_events
    where action = 'root_owner_bootstrapped'
      and subject_user_id = p_user_id
  ) then
    insert into private.control_plane_audit_events (
      actor_user_id, subject_user_id, action, next_role
    ) values (
      p_user_id, p_user_id, 'root_owner_bootstrapped', 'owner'
    );
  end if;

  return jsonb_build_object(
    'userReference', private.control_plane_user_reference(p_user_id),
    'role', 'owner',
    'isRootOwner', true,
    'status', 'active'
  );
end;
$$;

revoke all on function private.bootstrap_control_plane_root_owner(uuid)
  from public, anon, authenticated;
grant execute on function private.bootstrap_control_plane_root_owner(uuid)
  to service_role;

create or replace function public.get_my_control_plane_access()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_user_id uuid := auth.uid();
  v_role text;
  v_is_root boolean;
  v_grants jsonb;
begin
  v_role := private.require_control_plane_operator(null);

  select is_root_owner into v_is_root
  from private.control_plane_operators
  where user_id = v_user_id;

  select coalesce(jsonb_agg(jsonb_build_object(
    'grantCode', grant_code,
    'permissionKey', permission_key,
    'productKey', product_key,
    'moduleKey', module_key,
    'environmentKey', environment_key,
    'regionKey', region_key,
    'organizationId', organization_id,
    'dataClassification', data_classification,
    'expiresAt', expires_at
  ) order by granted_at desc), '[]'::jsonb)
  into v_grants
  from private.control_plane_permission_grants
  where user_id = v_user_id
    and revoked_at is null
    and (expires_at is null or expires_at > now());

  return jsonb_build_object(
    'userReference', private.control_plane_user_reference(v_user_id),
    'role', v_role,
    'isRootOwner', coalesce(v_is_root, false),
    'sessionAssurance', 'aal2',
    'grants', v_grants
  );
end;
$$;

revoke all on function public.get_my_control_plane_access()
  from public, anon;
grant execute on function public.get_my_control_plane_access()
  to authenticated;

create or replace function public.create_control_plane_invitation(
  p_email text,
  p_role text,
  p_token_sha256 text,
  p_expires_in_hours integer default 72
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private, extensions
as $$
declare
  v_actor uuid := auth.uid();
  v_email text := lower(trim(coalesce(p_email, '')));
  v_email_hash bytea;
  v_token_hash bytea;
  v_invitation private.control_plane_invitations%rowtype;
begin
  perform private.require_control_plane_operator(array['owner']);

  if char_length(v_email) < 5 or char_length(v_email) > 254
    or v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'control_plane_invitation_email_invalid' using errcode = '22023';
  end if;

  if p_role not in ('admin', 'analyst', 'support') then
    raise exception 'control_plane_invitation_role_invalid' using errcode = '22023';
  end if;

  if p_expires_in_hours < 1 or p_expires_in_hours > 168 then
    raise exception 'control_plane_invitation_expiry_invalid' using errcode = '22023';
  end if;

  if p_token_sha256 !~ '^[a-f0-9]{64}$' then
    raise exception 'control_plane_invitation_token_invalid' using errcode = '22023';
  end if;

  v_email_hash := extensions.digest(convert_to(v_email, 'UTF8'), 'sha256');
  v_token_hash := decode(p_token_sha256, 'hex');

  update private.control_plane_invitations
  set status = 'expired'
  where status = 'pending' and expires_at <= now();

  update private.control_plane_invitations
  set status = 'revoked', revoked_at = now()
  where status = 'pending'
    and intended_email_sha256 = v_email_hash;

  insert into private.control_plane_invitations (
    token_sha256,
    intended_email_sha256,
    intended_email_masked,
    role,
    created_by,
    expires_at
  ) values (
    v_token_hash,
    v_email_hash,
    private.mask_control_plane_email(v_email),
    p_role,
    v_actor,
    now() + make_interval(hours => p_expires_in_hours)
  ) returning * into v_invitation;

  insert into private.control_plane_audit_events (
    actor_user_id, invitation_id, action, next_role
  ) values (
    v_actor, v_invitation.id, 'invitation_created', v_invitation.role
  );

  return jsonb_build_object(
    'invitationCode', v_invitation.invitation_code,
    'maskedEmail', v_invitation.intended_email_masked,
    'role', v_invitation.role,
    'expiresAt', v_invitation.expires_at
  );
end;
$$;

revoke all on function public.create_control_plane_invitation(text, text, text, integer)
  from public, anon;
grant execute on function public.create_control_plane_invitation(text, text, text, integer)
  to authenticated;

create or replace function public.accept_control_plane_invitation(
  p_token_sha256 text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private, extensions
as $$
declare
  v_user_id uuid := auth.uid();
  v_aal text := coalesce(auth.jwt()->>'aal', 'aal1');
  v_email text;
  v_email_hash bytea;
  v_token_hash bytea;
  v_invitation private.control_plane_invitations%rowtype;
begin
  if v_user_id is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;

  if v_aal <> 'aal2' then
    raise exception 'mfa_verification_required' using errcode = '42501';
  end if;

  if p_token_sha256 !~ '^[a-f0-9]{64}$' then
    raise exception 'control_plane_invitation_token_invalid' using errcode = '22023';
  end if;

  select lower(trim(email)) into v_email
  from auth.users
  where id = v_user_id
    and deleted_at is null
    and email_confirmed_at is not null;

  if v_email is null or v_email = '' then
    raise exception 'verified_email_required' using errcode = '42501';
  end if;

  if exists (
    select 1 from private.control_plane_operators where user_id = v_user_id
  ) then
    raise exception 'control_plane_operator_already_exists' using errcode = '23505';
  end if;

  v_email_hash := extensions.digest(convert_to(v_email, 'UTF8'), 'sha256');
  v_token_hash := decode(p_token_sha256, 'hex');

  update private.control_plane_invitations
  set status = 'expired'
  where status = 'pending' and expires_at <= now();

  select * into v_invitation
  from private.control_plane_invitations
  where token_sha256 = v_token_hash
    and intended_email_sha256 = v_email_hash
    and status = 'pending'
    and expires_at > now()
  for update;

  if v_invitation.id is null then
    raise exception 'control_plane_invitation_invalid' using errcode = '42501';
  end if;

  insert into private.control_plane_operators (
    user_id, role, is_root_owner, status, created_by
  ) values (
    v_user_id, v_invitation.role, false, 'active', v_invitation.created_by
  );

  update private.control_plane_invitations
  set status = 'accepted',
      accepted_by = v_user_id,
      accepted_at = now()
  where id = v_invitation.id;

  insert into private.control_plane_audit_events (
    actor_user_id, subject_user_id, invitation_id, action, next_role
  ) values (
    v_user_id, v_user_id, v_invitation.id, 'invitation_accepted', v_invitation.role
  );

  return jsonb_build_object(
    'userReference', private.control_plane_user_reference(v_user_id),
    'role', v_invitation.role,
    'status', 'active'
  );
end;
$$;

revoke all on function public.accept_control_plane_invitation(text)
  from public, anon;
grant execute on function public.accept_control_plane_invitation(text)
  to authenticated;

create or replace function public.grant_control_plane_permission(
  p_user_id uuid,
  p_permission_key text,
  p_product_key text default null,
  p_module_key text default null,
  p_environment_key text default null,
  p_region_key text default null,
  p_organization_id uuid default null,
  p_data_classification text default null,
  p_expires_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_grant private.control_plane_permission_grants%rowtype;
begin
  perform private.require_control_plane_operator(array['owner']);

  if not exists (
    select 1 from private.control_plane_operators
    where user_id = p_user_id and status = 'active' and disabled_at is null
  ) then
    raise exception 'control_plane_operator_not_found' using errcode = '22023';
  end if;

  insert into private.control_plane_permission_grants (
    user_id,
    permission_key,
    product_key,
    module_key,
    environment_key,
    region_key,
    organization_id,
    data_classification,
    granted_by,
    expires_at
  ) values (
    p_user_id,
    p_permission_key,
    nullif(trim(p_product_key), ''),
    nullif(trim(p_module_key), ''),
    nullif(trim(p_environment_key), ''),
    nullif(trim(p_region_key), ''),
    p_organization_id,
    nullif(trim(p_data_classification), ''),
    v_actor,
    p_expires_at
  ) returning * into v_grant;

  insert into private.control_plane_audit_events (
    actor_user_id, subject_user_id, grant_id, action, permission_key
  ) values (
    v_actor, p_user_id, v_grant.id, 'permission_granted', v_grant.permission_key
  );

  return jsonb_build_object(
    'grantCode', v_grant.grant_code,
    'userReference', private.control_plane_user_reference(p_user_id),
    'permissionKey', v_grant.permission_key,
    'expiresAt', v_grant.expires_at
  );
end;
$$;

