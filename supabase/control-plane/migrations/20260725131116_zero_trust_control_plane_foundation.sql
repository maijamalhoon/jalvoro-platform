begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to service_role;

create extension if not exists pgcrypto with schema extensions;

create table private.control_plane_operators (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null,
  is_root_owner boolean not null default false,
  status text not null default 'active',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  disabled_at timestamptz,
  disabled_by uuid references auth.users(id) on delete set null,
  constraint control_plane_operators_role_check check (
    role in ('owner', 'admin', 'analyst', 'support')
  ),
  constraint control_plane_operators_status_check check (
    status in ('active', 'disabled')
  ),
  constraint control_plane_root_owner_role_check check (
    not is_root_owner or role = 'owner'
  ),
  constraint control_plane_operator_disabled_check check (
    (status = 'disabled' and disabled_at is not null)
    or (status = 'active' and disabled_at is null)
  )
);

create unique index control_plane_single_root_owner_idx
  on private.control_plane_operators (is_root_owner)
  where is_root_owner;

create table private.control_plane_invitations (
  id uuid primary key default gen_random_uuid(),
  invitation_code text not null unique default (
    'CPI-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
  ),
  token_sha256 bytea not null unique,
  intended_email_sha256 bytea not null,
  intended_email_masked text not null,
  role text not null,
  status text not null default 'pending',
  created_by uuid not null references auth.users(id) on delete restrict,
  accepted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  accepted_at timestamptz,
  revoked_at timestamptz,
  constraint control_plane_invitation_code_check check (
    invitation_code ~ '^CPI-[A-F0-9]{12}$'
  ),
  constraint control_plane_invitation_token_hash_check check (
    octet_length(token_sha256) = 32
  ),
  constraint control_plane_invitation_email_hash_check check (
    octet_length(intended_email_sha256) = 32
  ),
  constraint control_plane_invitation_role_check check (
    role in ('admin', 'analyst', 'support')
  ),
  constraint control_plane_invitation_status_check check (
    status in ('pending', 'accepted', 'revoked', 'expired')
  ),
  constraint control_plane_invitation_expiry_check check (
    expires_at > created_at and expires_at <= created_at + interval '7 days'
  )
);

create table private.control_plane_permission_grants (
  id uuid primary key default gen_random_uuid(),
  grant_code text not null unique default (
    'CPG-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
  ),
  user_id uuid not null references auth.users(id) on delete cascade,
  permission_key text not null,
  product_key text,
  module_key text,
  environment_key text,
  region_key text,
  organization_id uuid,
  data_classification text,
  granted_by uuid not null references auth.users(id) on delete restrict,
  granted_at timestamptz not null default now(),
  expires_at timestamptz,
  revoked_at timestamptz,
  revoked_by uuid references auth.users(id) on delete set null,
  constraint control_plane_grant_code_check check (
    grant_code ~ '^CPG-[A-F0-9]{12}$'
  ),
  constraint control_plane_permission_key_check check (
    permission_key ~ '^[a-z][a-z0-9-]*(:[a-z][a-z0-9-]*){2,4}$'
  ),
  constraint control_plane_environment_check check (
    environment_key is null or environment_key in ('development', 'preview', 'production')
  ),
  constraint control_plane_classification_check check (
    data_classification is null
    or data_classification in ('public', 'internal', 'confidential', 'restricted')
  ),
  constraint control_plane_grant_expiry_check check (
    expires_at is null or expires_at > granted_at
  )
);

create unique index control_plane_active_grant_unique_idx
  on private.control_plane_permission_grants (
    user_id,
    permission_key,
    coalesce(product_key, ''),
    coalesce(module_key, ''),
    coalesce(environment_key, ''),
    coalesce(region_key, ''),
    coalesce(organization_id, '00000000-0000-0000-0000-000000000000'::uuid),
    coalesce(data_classification, '')
  )
  where revoked_at is null;

create table private.control_plane_audit_events (
  id bigint generated by default as identity primary key,
  event_code text not null unique default (
    'CPA-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 16))
  ),
  actor_user_id uuid references auth.users(id) on delete set null,
  subject_user_id uuid references auth.users(id) on delete set null,
  invitation_id uuid references private.control_plane_invitations(id) on delete set null,
  grant_id uuid references private.control_plane_permission_grants(id) on delete set null,
  action text not null,
  previous_role text,
  next_role text,
  permission_key text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 months'),
  constraint control_plane_audit_event_code_check check (
    event_code ~ '^CPA-[A-F0-9]{16}$'
  ),
  constraint control_plane_audit_action_check check (
    action in (
      'root_owner_bootstrapped',
      'invitation_created',
      'invitation_revoked',
      'invitation_accepted',
      'permission_granted',
      'permission_revoked',
      'operator_role_changed',
      'operator_disabled',
      'operator_restored'
    )
  ),
  constraint control_plane_audit_role_check check (
    (previous_role is null or previous_role in ('owner', 'admin', 'analyst', 'support'))
    and (next_role is null or next_role in ('owner', 'admin', 'analyst', 'support'))
  ),
  constraint control_plane_audit_expiry_check check (expires_at > created_at)
);

