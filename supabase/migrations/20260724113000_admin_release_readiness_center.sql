create or replace function private.revoke_admin_release(p_release_code text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_role text;
  v_release_code text := upper(trim(coalesce(p_release_code, '')));
  v_release private.admin_release_approvals%rowtype;
begin
  select role into v_actor_role
  from private.platform_admins
  where user_id = v_actor and disabled_at is null;

  if v_actor is null or v_actor_role <> 'owner' then
    raise exception 'owner_release_approval_required' using errcode = '42501';
  end if;

  if v_release_code !~ '^REL-[A-F0-9]{12}$' then
    raise exception 'release_code_invalid' using errcode = '22023';
  end if;

  update private.admin_release_approvals
  set revoked_at = now()
  where release_code = v_release_code
    and revoked_at is null
    and expires_at > now()
  returning * into v_release;

  if not found then
    raise exception 'release_approval_not_found' using errcode = 'P0002';
  end if;

  insert into private.admin_release_approval_audit (
    release_code,
    revision_sha,
    environment,
    actor_user_id,
    action,
    readiness_digest
  ) values (
    v_release.release_code,
    v_release.revision_sha,
    v_release.environment,
    v_actor,
    'revoked',
    v_release.readiness_digest
  );

  return jsonb_build_object(
    'releaseCode', v_release.release_code,
    'revoked', true
  );
end;
$$;

