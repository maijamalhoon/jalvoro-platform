create or replace function private.purge_expired_admin_release_approvals()
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
declare
  v_approvals_deleted bigint := 0;
  v_audit_deleted bigint := 0;
begin
  delete from private.admin_release_approval_audit
  where expires_at <= now();
  get diagnostics v_audit_deleted = row_count;

  delete from private.admin_release_approvals
  where expires_at <= now() - interval '24 months';
  get diagnostics v_approvals_deleted = row_count;

  return jsonb_build_object(
    'approvalRowsDeleted', v_approvals_deleted,
    'auditRowsDeleted', v_audit_deleted
  );
end;
