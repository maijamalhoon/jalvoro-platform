create or replace function private.get_admin_release_readiness_snapshot()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_role text;
  v_state jsonb;
  v_digest bytea;
begin
  select role into v_actor_role
  from private.platform_admins
  where user_id = v_actor and disabled_at is null;

  if v_actor is null or v_actor_role is null then
    raise exception 'admin_access_required' using errcode = '42501';
  end if;

  v_state := private.admin_release_database_state();
  v_digest := private.admin_release_database_state_digest();

  return jsonb_build_object(
    'approvalAllowed', v_actor_role = 'owner',
    'mode', case when v_actor_role = 'owner' then 'approve' else 'read_only' end,
    'approvalRetentionMonths', 24,
    'approvalValidityHours', 24,
    'rawIdentityReturned', false,
    'financeContentReturned', false,
    'runtimeSecretsStored', false,
    'freeTextStored', false,
    'database', v_state->'database',
    'approvals', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'releaseCode', rows.release_code,
          'revisionSha', rows.revision_sha,
          'environment', rows.environment,
          'status', case
            when rows.revoked_at is not null then 'revoked'
            when rows.expires_at <= now() then 'expired'
            else 'active'
          end,
          'databaseState', case
            when rows.readiness_digest = v_digest then 'verified'
            else 'stale'
          end,
          'approvedAt', rows.approved_at,
          'expiresAt', rows.expires_at,
          'revokedAt', rows.revoked_at
        ) order by rows.approved_at desc
      )
      from (
        select *
        from private.admin_release_approvals
        order by approved_at desc
        limit 10
      ) rows
    ), '[]'::jsonb)
  );
end;
$$;

revoke all on function private.get_admin_release_readiness_snapshot()
  from public, anon;
grant execute on function private.get_admin_release_readiness_snapshot()
  to authenticated;

create or replace function private.approve_admin_release(
  p_revision_sha text,
  p_environment text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_role text;
  v_revision_sha text := lower(trim(coalesce(p_revision_sha, '')));
  v_environment text := lower(trim(coalesce(p_environment, '')));
  v_state jsonb;
  v_digest bytea;
  v_release private.admin_release_approvals%rowtype;
  v_superseded private.admin_release_approvals%rowtype;
begin
  select role into v_actor_role
  from private.platform_admins
  where user_id = v_actor and disabled_at is null;

  if v_actor is null or v_actor_role <> 'owner' then
    raise exception 'owner_release_approval_required' using errcode = '42501';
  end if;

  if v_revision_sha !~ '^[a-f0-9]{40}$' then
    raise exception 'release_revision_invalid' using errcode = '22023';
  end if;

  if v_environment not in ('production', 'preview') then
    raise exception 'release_environment_invalid' using errcode = '22023';
  end if;

  v_state := private.admin_release_database_state();

  if (v_state->'database'->>'requiredMigrationsApplied')::bigint
      <> (v_state->'database'->>'requiredMigrationsTotal')::bigint
    or (v_state->'database'->>'rlsTablesProtected')::bigint
      <> (v_state->'database'->>'rlsTablesTotal')::bigint
    or (v_state->'database'->>'directAccessDenied')::bigint
      <> (v_state->'database'->>'directAccessChecksTotal')::bigint
    or (v_state->'database'->>'appendOnlyTriggers')::bigint
      <> (v_state->'database'->>'appendOnlyTriggersExpected')::bigint
    or (v_state->'database'->>'requiredFunctionsPresent')::bigint
      <> (v_state->'database'->>'requiredFunctionsTotal')::bigint
    or (v_state->'database'->>'permissionChecksPassed')::bigint
      <> (v_state->'database'->>'permissionChecksTotal')::bigint
    or (v_state->'blockers'->>'overduePrivacy')::bigint > 0
    or (v_state->'blockers'->>'criticalIncidents')::bigint > 0
    or (v_state->'blockers'->>'overdueIncidents')::bigint > 0
    or (v_state->'blockers'->>'integrityMismatches')::bigint > 0
    or (v_state->'blockers'->>'failedWebhooks24h')::bigint > 0
    or (v_state->'blockers'->>'failedOperations7d')::bigint > 0
    or (v_state->'blockers'->>'activeOwners')::bigint < 1 then
    raise exception 'release_readiness_blocked' using errcode = '55000';
  end if;

  v_digest := private.admin_release_database_state_digest();

  for v_superseded in
    update private.admin_release_approvals
    set revoked_at = now()
    where revoked_at is null and expires_at > now()
    returning *
  loop
    insert into private.admin_release_approval_audit (
      release_code,
      revision_sha,
      environment,
      actor_user_id,
      action,
      readiness_digest
    ) values (
      v_superseded.release_code,
      v_superseded.revision_sha,
      v_superseded.environment,
      v_actor,
      'superseded',
      v_superseded.readiness_digest
    );
  end loop;

  insert into private.admin_release_approvals (
    revision_sha,
    environment,
    readiness_digest,
    approved_by,
    approved_at,
    expires_at
  ) values (
    v_revision_sha,
    v_environment,
    v_digest,
    v_actor,
    now(),
    now() + interval '24 hours'
  ) returning * into v_release;

  insert into private.admin_release_approval_audit (
    release_code,
    revision_sha,
    environment,
    actor_user_id,
    action,
    readiness_digest
  ) values (
    v_release.release_code,
    v_release.revision_sha,
    v_release.environment,
    v_actor,
    'approved',
    v_release.readiness_digest
  );

  return jsonb_build_object(
    'releaseCode', v_release.release_code,
    'revisionSha', v_release.revision_sha,
    'environment', v_release.environment,
    'approved', true,
    'expiresAt', v_release.expires_at
  );
end;
$$;

