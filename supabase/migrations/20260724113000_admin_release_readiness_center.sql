create table if not exists private.admin_release_approvals (
  release_code text primary key default (
    'REL-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
  ),
  revision_sha text not null,
  environment text not null,
  readiness_digest bytea not null,
  approved_by uuid not null references auth.users(id) on delete restrict,
  approved_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours'),
  revoked_at timestamptz,
  constraint admin_release_approvals_code_check check (
    release_code ~ '^REL-[A-F0-9]{12}$'
  ),
  constraint admin_release_approvals_revision_check check (
    revision_sha ~ '^[a-f0-9]{40}$'
  ),
  constraint admin_release_approvals_environment_check check (
    environment in ('production', 'preview')
  ),
  constraint admin_release_approvals_digest_check check (
    octet_length(readiness_digest) = 32
  ),
  constraint admin_release_approvals_expiry_check check (
    expires_at > approved_at
    and expires_at <= approved_at + interval '24 hours'
  ),
  constraint admin_release_approvals_revocation_check check (
    revoked_at is null or revoked_at >= approved_at
  )
);

comment on table private.admin_release_approvals is
  'Short-lived Owner approvals for an exact deployment revision and database readiness digest. Stores no free text, user identity output, finance content, runtime secret or provider payload.';

create table if not exists private.admin_release_approval_audit (
  id bigint generated by default as identity primary key,
  release_code text not null,
  revision_sha text not null,
  environment text not null,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  readiness_digest bytea not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 months'),
  constraint admin_release_approval_audit_code_check check (
    release_code ~ '^REL-[A-F0-9]{12}$'
  ),
  constraint admin_release_approval_audit_revision_check check (
    revision_sha ~ '^[a-f0-9]{40}$'
  ),
  constraint admin_release_approval_audit_environment_check check (
    environment in ('production', 'preview')
  ),
  constraint admin_release_approval_audit_action_check check (
    action in ('approved', 'revoked', 'superseded')
  ),
  constraint admin_release_approval_audit_digest_check check (
    octet_length(readiness_digest) = 32
  ),
  constraint admin_release_approval_audit_expiry_check check (
    expires_at > created_at
  )
);

comment on table private.admin_release_approval_audit is
  'Append-only release approval transitions with 24-month retention and no free text or sensitive user data.';

