create or replace function private.purge_expired_admin_compliance_reviews()
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
declare
  v_reviews_deleted bigint := 0;
  v_audit_deleted bigint := 0;
begin
  delete from private.admin_compliance_review_audit
  where expires_at <= now();
  get diagnostics v_audit_deleted = row_count;

  delete from private.admin_compliance_audit_reviews
  where expires_at <= now();
  get diagnostics v_reviews_deleted = row_count;

  return jsonb_build_object(
    'reviewRowsDeleted', v_reviews_deleted,
    'auditRowsDeleted', v_audit_deleted
  );
end;
$$;

