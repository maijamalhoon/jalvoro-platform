create table if not exists private.admin_compliance_audit_reviews (
  event_code text primary key,
  domain text not null,
  status text not null,
  source_digest bytea not null,
  reviewed_by uuid not null references auth.users(id) on delete restrict,
  reviewed_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 months'),
  constraint admin_compliance_audit_reviews_code_check check (
    event_code ~ '^AUD-[A-F0-9]{12}$'
  ),
  constraint admin_compliance_audit_reviews_domain_check check (
    domain in ('privacy', 'billing', 'access', 'incident')
  ),
  constraint admin_compliance_audit_reviews_status_check check (
    status in ('reviewed', 'flagged')
  ),
  constraint admin_compliance_audit_reviews_digest_check check (
    octet_length(source_digest) = 32
  ),
  constraint admin_compliance_audit_reviews_expiry_check check (
    expires_at > reviewed_at
  )
);

