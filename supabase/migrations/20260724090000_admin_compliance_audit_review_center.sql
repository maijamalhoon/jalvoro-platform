create or replace function private.admin_compliance_event_code(
  p_domain text,
  p_source_id bigint
)
returns text
language sql
immutable
strict
set search_path = pg_catalog, extensions
as $$
  select 'AUD-' || upper(substr(
    encode(
      extensions.digest(
        convert_to(p_domain || ':' || p_source_id::text, 'UTF8'),
        'sha256'
      ),
      'hex'
    ),
    1,
    12
  ));
$$;

revoke all on function private.admin_compliance_event_code(text, bigint)
  from public, anon, authenticated;
