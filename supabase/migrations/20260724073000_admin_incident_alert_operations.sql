create policy platform_security_incident_audit_deny_direct
  on private.platform_security_incident_audit
  for all
  to anon, authenticated
  using (false)
  with check (false);

grant select, insert, update, delete
  on private.platform_security_incidents,
  private.platform_security_incident_audit
  to service_role;
grant usage, select on sequence private.platform_security_incident_audit_id_seq
  to service_role;

