begin;

create table if not exists private.platform_security_incidents (
  id uuid primary key default gen_random_uuid(),
  incident_code text not null unique default (
    'INC-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))
  ),
  category text not null,
  severity text not null,
  status text not null default 'open',
  source text not null,
  source_reference text,
  assigned_to uuid references auth.users(id) on delete set null,
  created_by uuid not null references auth.users(id) on delete restrict,
  acknowledged_by uuid references auth.users(id) on delete set null,
  resolved_by uuid references auth.users(id) on delete set null,
  resolution_code text,
  due_at timestamptz,
  acknowledged_at timestamptz,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  expires_at timestamptz,
  constraint platform_security_incidents_code_check check (
    incident_code ~ '^INC-[A-F0-9]{12}$'
  ),
  constraint platform_security_incidents_category_check check (
    category in (
      'access_governance',
      'privacy_deadline',
      'billing_pipeline',
      'availability',
      'data_boundary',
      'retention',
      'manual_review'
    )
  ),
  constraint platform_security_incidents_severity_check check (
    severity in ('low', 'medium', 'high', 'critical')
  ),
  constraint platform_security_incidents_status_check check (
    status in ('open', 'acknowledged', 'investigating', 'monitoring', 'resolved', 'dismissed')
  ),
  constraint platform_security_incidents_source_check check (
    source in ('posture', 'access', 'privacy', 'billing', 'system', 'manual')
  ),
  constraint platform_security_incidents_source_reference_check check (
    source_reference is null
    or source_reference ~ '^(PRV|ADM|AIN|USR)-[A-F0-9]{12}$'
  ),
  constraint platform_security_incidents_resolution_check check (
    (
      status in ('resolved', 'dismissed')
      and resolution_code in (
        'mitigated',
        'false_positive',
        'duplicate',
        'accepted_risk',
        'no_action_required',
        'superseded'
      )
      and resolved_at is not null
      and resolved_by is not null
      and expires_at is not null
    )
    or (
      status not in ('resolved', 'dismissed')
      and resolution_code is null
      and resolved_at is null
      and resolved_by is null
      and expires_at is null
    )
  ),
  constraint platform_security_incidents_acknowledgement_check check (
    (acknowledged_at is null and acknowledged_by is null)
    or (acknowledged_at is not null and acknowledged_by is not null)
  ),
  constraint platform_security_incidents_due_check check (
    due_at is null or due_at > created_at - interval '1 day'
  ),
  constraint platform_security_incidents_expiry_check check (
    expires_at is null or expires_at > resolved_at
  )
);

comment on table private.platform_security_incidents is
  'Structured Admin Panel incident workflow. Stores controlled operational metadata only; no free-text descriptions, raw IP addresses, session replay, user identities, finance content, provider payloads, credentials, or arbitrary JSON.';

create table if not exists private.platform_security_incident_audit (
  id bigint generated by default as identity primary key,
  incident_id uuid not null references private.platform_security_incidents(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  previous_status text,
  next_status text,
  previous_severity text,
  next_severity text,
  previous_assignment uuid references auth.users(id) on delete set null,
  next_assignment uuid references auth.users(id) on delete set null,
  resolution_code text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 months'),
  constraint platform_security_incident_audit_action_check check (
    action in ('created', 'workflow_updated')
  ),
  constraint platform_security_incident_audit_status_check check (
    previous_status is null or previous_status in ('open', 'acknowledged', 'investigating', 'monitoring', 'resolved', 'dismissed')
  ),
  constraint platform_security_incident_audit_next_status_check check (
    next_status is null or next_status in ('open', 'acknowledged', 'investigating', 'monitoring', 'resolved', 'dismissed')
  ),
  constraint platform_security_incident_audit_previous_severity_check check (
    previous_severity is null or previous_severity in ('low', 'medium', 'high', 'critical')
  ),
  constraint platform_security_incident_audit_next_severity_check check (
    next_severity is null or next_severity in ('low', 'medium', 'high', 'critical')
  ),
  constraint platform_security_incident_audit_resolution_check check (
    resolution_code is null or resolution_code in (
      'mitigated',
      'false_positive',
      'duplicate',
      'accepted_risk',
      'no_action_required',
      'superseded'
    )
  ),
  constraint platform_security_incident_audit_expiry_check check (
    expires_at > created_at
  )
);

comment on table private.platform_security_incident_audit is
  'Structured incident transition audit with 24-month retention. Contains no free text, raw IP, user identity, finance content, credentials, provider payloads, or arbitrary metadata.';

alter table private.platform_security_incidents enable row level security;
alter table private.platform_security_incident_audit enable row level security;

revoke all on private.platform_security_incidents,
