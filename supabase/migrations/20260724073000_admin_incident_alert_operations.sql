create or replace function private.get_platform_security_incident_snapshot()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_role text;
begin
  select role into v_actor_role
  from private.platform_admins
  where user_id = v_actor and disabled_at is null;

  if v_actor is null or v_actor_role is null then
    raise exception 'admin_access_required' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'operationsAllowed', v_actor_role in ('owner', 'admin'),
    'freeTextStored', false,
    'rawIpStored', false,
    'sessionReplayStored', false,
    'userIdentityReturned', false,
    'financeContentStored', false,
    'providerPayloadStored', false,
    'counts', jsonb_build_object(
      'open', (select count(*)::bigint from private.platform_security_incidents where status = 'open'),
      'acknowledged', (select count(*)::bigint from private.platform_security_incidents where status = 'acknowledged'),
      'investigating', (select count(*)::bigint from private.platform_security_incidents where status = 'investigating'),
      'monitoring', (select count(*)::bigint from private.platform_security_incidents where status = 'monitoring'),
      'criticalOpen', (
        select count(*)::bigint
        from private.platform_security_incidents
        where severity = 'critical' and status not in ('resolved', 'dismissed')
      ),
      'overdueOpen', (
        select count(*)::bigint
        from private.platform_security_incidents
        where due_at < now() and status not in ('resolved', 'dismissed')
      ),
      'resolved30d', (
        select count(*)::bigint
        from private.platform_security_incidents
        where status = 'resolved' and resolved_at >= now() - interval '30 days'
      ),
      'auditEvents30d', (
        select count(*)::bigint
        from private.platform_security_incident_audit
        where created_at >= now() - interval '30 days'
      ),
      'expiredAuditPending', (
        select count(*)::bigint
        from private.platform_security_incident_audit
        where expires_at <= now()
      ),
      'expiredIncidentsPending', (
        select count(*)::bigint
        from private.platform_security_incidents
        where expires_at is not null and expires_at <= now()
      )
    ),
    'queue', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'incidentCode', rows.incident_code,
          'category', rows.category,
          'severity', rows.severity,
          'status', rows.status,
          'source', rows.source,
          'sourceReference', rows.source_reference,
          'createdAt', rows.created_at,
          'dueAt', rows.due_at,
          'assigned', rows.assigned_to is not null,
          'assignedToMe', rows.assigned_to = v_actor,
          'overdue', rows.due_at is not null and rows.due_at < now(),
          'manageable', (
            v_actor_role = 'owner'
            or rows.assigned_to is null
            or rows.assigned_to = v_actor
          )
        ) order by
          case rows.severity
            when 'critical' then 1
            when 'high' then 2
            when 'medium' then 3
            else 4
          end,
          rows.due_at nulls last,
          rows.created_at desc
      )
      from (
        select *
        from private.platform_security_incidents
        where status not in ('resolved', 'dismissed')
        order by
          case severity
            when 'critical' then 1
            when 'high' then 2
            when 'medium' then 3
            else 4
          end,
          due_at nulls last,
          created_at desc
        limit 40
      ) rows
    ), '[]'::jsonb)
  );
end;
$$;

revoke all on function private.get_platform_security_incident_snapshot()
  from public, anon;
grant execute on function private.get_platform_security_incident_snapshot()
  to authenticated;

create or replace function private.purge_expired_platform_security_incidents()
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
declare
  v_audit_deleted bigint := 0;
  v_incidents_deleted bigint := 0;
begin
  if current_user <> 'service_role' and session_user <> 'service_role' then
    raise exception 'service_role_required' using errcode = '42501';
  end if;

  delete from private.platform_security_incident_audit
  where expires_at <= now();
  get diagnostics v_audit_deleted = row_count;

  delete from private.platform_security_incidents
  where expires_at is not null and expires_at <= now();
  get diagnostics v_incidents_deleted = row_count;

  return jsonb_build_object(
    'auditRowsDeleted', v_audit_deleted,
    'incidentRowsDeleted', v_incidents_deleted
  );
end;
$$;

revoke all on function private.purge_expired_platform_security_incidents()
  from public, anon, authenticated;
grant execute on function private.purge_expired_platform_security_incidents()
  to service_role;

