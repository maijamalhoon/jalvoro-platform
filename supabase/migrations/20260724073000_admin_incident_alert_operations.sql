  on private.platform_security_incident_audit (expires_at);

create or replace function private.create_platform_security_incident(
  p_category text,
  p_severity text,
  p_source text,
  p_source_reference text default null,
  p_due_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, auth, private
as $$
declare
  v_actor uuid := auth.uid();
  v_actor_role text;
  v_incident private.platform_security_incidents%rowtype;
  v_source_reference text := nullif(upper(trim(coalesce(p_source_reference, ''))), '');
begin
  select role into v_actor_role
  from private.platform_admins
  where user_id = v_actor and disabled_at is null;

  if v_actor is null or v_actor_role not in ('owner', 'admin') then
    raise exception 'incident_operator_access_required' using errcode = '42501';
  end if;

  if p_category not in (
    'access_governance', 'privacy_deadline', 'billing_pipeline',
    'availability', 'data_boundary', 'retention', 'manual_review'
  ) then
    raise exception 'incident_category_invalid' using errcode = '22023';
  end if;

  if p_severity not in ('low', 'medium', 'high', 'critical') then
    raise exception 'incident_severity_invalid' using errcode = '22023';
  end if;

  if p_source not in ('posture', 'access', 'privacy', 'billing', 'system', 'manual') then
    raise exception 'incident_source_invalid' using errcode = '22023';
  end if;

  if v_source_reference is not null
    and v_source_reference !~ '^(PRV|ADM|AIN|USR)-[A-F0-9]{12}$' then
    raise exception 'incident_source_reference_invalid' using errcode = '22023';
  end if;

  if p_due_at is not null
    and (p_due_at <= now() or p_due_at > now() + interval '365 days') then
    raise exception 'incident_due_at_invalid' using errcode = '22023';
  end if;

  insert into private.platform_security_incidents (
    category,
    severity,
    source,
    source_reference,
    assigned_to,
    created_by,
    due_at
  ) values (
    p_category,
    p_severity,
    p_source,
    v_source_reference,
    v_actor,
    v_actor,
    p_due_at
  ) returning * into v_incident;

  insert into private.platform_security_incident_audit (
    incident_id,
    actor_user_id,
    action,
    next_status,
    next_severity,
    next_assignment
  ) values (
    v_incident.id,
    v_actor,
    'created',
    v_incident.status,
    v_incident.severity,
    v_incident.assigned_to
  );

  return jsonb_build_object(
    'incidentCode', v_incident.incident_code,
    'created', true
  );
end;
$$;

